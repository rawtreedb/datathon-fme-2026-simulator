"""RawTree setup for the challenge. Needs an admin key in RAWTREE_API_KEY.

    python admin.py init                     # shared databases + tables
    python admin.py load data/               # upload catalog + history generated by generate.py
    python admin.py add-team 3               # create the next 3 teams (db, tables, role, key) -> teams.csv
    python admin.py add-team team_07         # or by name (idempotent)
    python admin.py reset-live               # wipe live tables after a dry run
    python admin.py status                   # row counts of every table + team databases
    python admin.py sql "SELECT ..."         # any query with the admin key, one JSON row per line
    python admin.py leaderboard-key          # read-only key for the Vercel leaderboard (outcomes only)
    python admin.py remove-team team_99      # delete a (test) team: database, role and key
    python admin.py rotate-key team_07       # leaked key: new key for the same team, data untouched
"""
import csv
import gzip
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

from rawtree import RawTree

SHARED = {  # database -> {table: sorting key}
    "shop": {"catalog": "product_id", "history_sessions": "ts", "history_events": "ts",
             "requests": "ts", "events": "ts", "catalog_updates": "ts"},
    "organizer": {"outcomes": "t"},
}
LIVE = [("shop", "requests"), ("shop", "events"), ("shop", "catalog_updates"), ("organizer", "outcomes")]
TEAM_TABLES = {"submissions": "request_id", "feedback": "ts", "scratch": None}
SENTINEL = {  # one row so the columns exist before the first real insert
    "submissions": {"request_id": "__init__", "items": [], "model_version": "init"},
    "feedback": {"request_id": "__init__", "ts": "2026-01-01T00:00:00.000Z", "shown": [], "served_by": "init", "fallback_reason": "",
                 "latency_ms": 0, "clicked": "", "purchased": "", "revenue_eur": 0.0, "model_version": "init"},
}
TEAMS_CSV = Path(__file__).with_name("teams.csv")


def ensure_db(rt, name):
    if name not in rt.databases():
        rt.create_database(name)


def ensure_table(rt, db, table, key):
    if table not in rt.tables(db):
        rt.create_table(db, table, key)
        return True
    return False


def init(rt):
    for db, tables in SHARED.items():
        ensure_db(rt, db)
        for t, key in tables.items():
            ensure_table(rt, db, t, key)
    print("ok:", {db: rt.tables(db) for db in SHARED})


def load(rt, folder):
    """Replaces the tables it loads, so it can be re-run."""
    done = set()
    for f in sorted(Path(folder).glob("*.jsonl.gz")):
        table = f.name.split("-")[0]
        if table not in done:
            if table in rt.tables("shop"):
                rt.drop_table("shop", table)
            ensure_table(rt, "shop", table, SHARED["shop"][table])
            done.add(table)
        rows = [json.loads(line) for line in gzip.open(f, "rt")]
        for i in range(0, len(rows), 50_000):
            rt.insert("shop", table, rows[i:i + 50_000], gz=True)
        print(f"{f.name}: {len(rows)} rows -> shop.{table}")


def add_team(rt, team):
    ensure_db(rt, team)
    for t, key in TEAM_TABLES.items():
        if ensure_table(rt, team, t, key) and t in SENTINEL:
            rt.insert(team, t, [SENTINEL[t]])
    if not any(r["team_id"] == team for r in read_teams()):
        rt.execute(f"CREATE ROLE {team}")
        rt.execute(f"GRANT SELECT ON shop.* TO {team}")
        rt.execute(f"GRANT SELECT, INSERT ON {team}.* TO {team}")
        token = rt.create_key(team, [team], team)["token"]
        with TEAMS_CSV.open("a", newline="") as f:
            csv.writer(f).writerow([team, token, datetime.now(timezone.utc).isoformat(timespec="seconds")])
    row = next(r for r in read_teams() if r["team_id"] == team)
    print(f"TEAM_ID={team}  RAWTREE_API_KEY={row['key']}")


def read_teams():
    if not TEAMS_CSV.exists():
        return []
    return [dict(zip(["team_id", "key", "created_at"], r)) for r in csv.reader(TEAMS_CSV.open())]


def remove_team(rt, team):
    rows = read_teams()
    for r in rows:
        if r["team_id"] == team:
            rt._call("DELETE", f"/v1/keys/{r['key']}")
    rt.execute(f"DROP ROLE IF EXISTS {team}")
    if team in rt.databases():
        rt._call("DELETE", f"/v1/databases/{team}")
    with TEAMS_CSV.open("w", newline="") as f:
        csv.writer(f).writerows([r["team_id"], r["key"], r["created_at"]] for r in rows if r["team_id"] != team)
    print(f"removed {team}")


def rotate_key(rt, team):
    rows = read_teams()
    old = next(r for r in rows if r["team_id"] == team)
    rt._call("DELETE", f"/v1/keys/{old['key']}")
    old["key"] = rt.create_key(team, [team], team)["token"]
    with TEAMS_CSV.open("w", newline="") as f:
        csv.writer(f).writerows([r["team_id"], r["key"], r["created_at"]] for r in rows)
    print(f"TEAM_ID={team}  RAWTREE_API_KEY={old['key']}")


def leaderboard_key(rt):
    rt.execute("CREATE ROLE leaderboard")
    rt.execute("GRANT SELECT ON organizer.outcomes TO leaderboard")
    print("RAWTREE_API_KEY=" + rt.create_key("leaderboard", ["leaderboard"], "organizer")["token"])


def reset_live(rt):
    for db, t in LIVE:
        if t in rt.tables(db):
            rt.drop_table(db, t)
        ensure_table(rt, db, t, SHARED[db][t])
    for r in read_teams():
        for t in ("submissions", "feedback"):
            rt.drop_table(r["team_id"], t)
            ensure_table(rt, r["team_id"], t, TEAM_TABLES[t])
            rt.insert(r["team_id"], t, [SENTINEL[t]])
    print("live tables reset")


def status(rt):
    for db, tables in SHARED.items():
        for t in tables:
            print(f"{db}.{t}: {count(rt, db, t)}")
    for r in read_teams():
        print(r["team_id"], {t: count(rt, r["team_id"], t) for t in ("submissions", "feedback")})
    print("team databases (the simulator serves all of them):", [d for d in rt.databases() if d.startswith("team_")])


def count(rt, db, t):
    try:
        return rt.query(f"SELECT count() AS n FROM {db}.{t}")[0]["n"]
    except RuntimeError as e:
        return f"ERROR {str(e)[:80]}"


def main():
    rt = RawTree()
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd == "init":
        init(rt)
    elif cmd == "load":
        load(rt, args[0])
    elif cmd == "add-team":
        if len(args) == 1 and args[0].isdigit():
            # highest number + 1, not row count: after a remove-team, a count would reuse a live team_NN and print its key
            start = max([int(r["team_id"][5:]) for r in read_teams() if r["team_id"][5:].isdigit()], default=0) + 1
            args = [f"team_{k:02d}" for k in range(start, start + int(args[0]))]
        for team in args:
            add_team(rt, team)
    elif cmd == "reset-live":
        reset_live(rt)
    elif cmd == "status":
        status(rt)
    elif cmd == "sql":
        for row in rt.query(args[0]):
            print(json.dumps(row, default=str))
    elif cmd == "remove-team":
        for team in args:
            remove_team(rt, team)
    elif cmd == "rotate-key":
        for team in args:
            rotate_key(rt, team)
    elif cmd == "leaderboard-key":
        leaderboard_key(rt)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
